def normalize_licence_label(value: object) -> str:
    """Normalize a license label for exact allowlist matching, not legal parsing."""
    if not isinstance(value, str):
        return ""
    v = value.casefold()
    for ch in ("_", "-", ".", "/", ",", ";", "(", ")", "[", "]"):
        v = v.replace(ch, " ")
    return " ".join(v.split())


