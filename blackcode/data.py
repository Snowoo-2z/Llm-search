# Déduplication : exacte (SHA-1 normalisé) + quasi (SimHash 64 bits, LSH 4x16)
def normalize(text: str) -> str:
    return "\n".join(ln.rstrip() for ln in text.splitlines() if ln.strip())


def _crc(part: str) -> int:
    return zlib.crc32(part.encode("utf-8", "ignore"))


_SHIFTS = np.arange(64, dtype=np.uint64)


def _hash_grams(grams: list[str]) -> np.ndarray:
    return np.fromiter(
        ((int(_crc(g)) << 32) | _crc(g + "\x01") for g in grams),
        dtype=np.uint64, count=len(grams),
    )


def simhash64(text: str, shingles: int = 2) -> int:
    """SimHash 64 bits sur des shingles de *lignes* (rapide, ~0,5 ms/doc).

    Les lignes sont plus stables que les mots pour du code : un fichier recopié
    avec quelques lignes changées garde le même voisinage.
    """
    lines = [ln.strip() for ln in normalize(text).splitlines()]
    if len(lines) < shingles:
        lines = text.split()
    if not lines:
        return 0
    if len(lines) < shingles:
        return (int(_crc(text)) << 32) | _crc(text + "\x01")
    grams = ["\x1f".join(lines[i:i + shingles])
             for i in range(len(lines) - shingles + 1)]
    hashes = _hash_grams(grams)
    bits = ((hashes[:, None] >> _SHIFTS) & np.uint64(1)).astype(np.int16)
    votes = bits.sum(axis=0) * 2 - len(hashes)
    out = 0
    for bit in np.nonzero(votes > 0)[0]:
        out |= 1 << int(bit)
    return out


def hamming(a: int, b: int) -> int:
    return (a ^ b).bit_count()


_TRIPLE_DOUBLE = chr(34) * 3
_TRIPLE_SINGLE = chr(39) * 3

_COMMENT_RE = [
    re.compile(r"#[^\n]*"),
    re.compile(r"//[^\n]*"),
    re.compile(r"/\*.*?\*/", re.S),
    re.compile(_TRIPLE_DOUBLE + r"[\s\S]*?" + _TRIPLE_DOUBLE),
    re.compile(_TRIPLE_SINGLE + r"[\s\S]*?" + _TRIPLE_SINGLE),
]


def code_signature(text: str) -> str:
    """Empreinte du code *sans* commentaires, docstrings ni espaces.

    Attrape le cas le plus fréquent de quasi-doublon : le même fichier recopié
    avec un en-tête de licence ou une docstring différente. Aucun faux positif
    possible : même empreinte ⇒ même code.
    """
    stripped = text
    for pattern in _COMMENT_RE:
        stripped = pattern.sub("", stripped)
    stripped = re.sub(r"\s+", "", stripped)
    return hashlib.sha1(stripped.encode("utf-8", "ignore")).hexdigest()


class Deduper:
    """Exact + quasi-duplicata, en mémoire. ~200 k documents tiennent dans <1 Go."""

    BANDS = 8
    WIDTH = 8
    THRESHOLD = 6

    def __init__(self, near: bool = True):
        self.near = near
        self._exact: set[str] = set()
        self._signatures: set[str] = set()
        self._hashes: list[int] = []
        self._bands: list[dict[int, list[int]]] = [{} for _ in range(self.BANDS)]

    def check(self, text: str) -> str | None:
        digest = hashlib.sha1(normalize(text).encode("utf-8", "ignore")).hexdigest()
        if digest in self._exact:
            return "exact"
        if self.near:
            signature = code_signature(text)
            if signature in self._signatures:
                return "quasi"
            self._signatures.add(signature)
            h = simhash64(text)
            for k in range(self.BANDS):
                key = (h >> (k * self.WIDTH)) & 0xFFFF
                for idx in self._bands[k].get(key, ())[:32]:
                    if hamming(h, self._hashes[idx]) <= self.THRESHOLD:
                        return "quasi"
            self._hashes.append(h)
            for k in range(self.BANDS):
                key = (h >> (k * self.WIDTH)) & 0xFFFF
                self._bands[k].setdefault(key, []).append(len(self._hashes) - 1)
        self._exact.add(digest)
        return None


