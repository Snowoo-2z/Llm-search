def _tool_call(name: str, args: dict) -> str:
    return "<|tool|>" + name + "(" + json.dumps(args, ensure_ascii=False) + ")"


def agentic_examples(func: Func, rng: random.Random) -> list[str]:
    """Crée des gabarits de programmation dont tout le dialogue est en français.

    Le code reste inchangé (syntaxe et identifiants du langage), mais aucun
    prompt ou message d'assistant anglais n'est généré. Ces traces sont
    synthétiques et ne prétendent pas provenir d'une exécution réelle.
    """
    path = f"src/module_{rng.randint(0, 40)}.py"
    body = func.body
    out: list[str] = []

    task = f"Explique en français le rôle de `{func.name}{func.signature}`."
    answer = (f"La fonction `{func.name}` reçoit les arguments indiqués par sa "
              f"signature. Voici son implémentation actuelle :\n{body}")
    out.append(f"<|system|>{SYSTEM_FR}<|user|>{task}<|assistant|>{answer}")

    task2 = f"Propose une version plus lisible de `{func.name}` et indique ce qu'elle renvoie."
    answer2 = (f"Voici le corps de `{func.name}` à examiner :\n{body}\n"
               "Je peux en simplifier la structure sans changer son comportement.")
    out.append(f"<|system|>{SYSTEM_FR}<|user|>{task2}<|assistant|>{answer2}")

    convo = (f"<|system|>{SYSTEM_FR}<|user|>Crée `{path}` avec la fonction "
             f"`{func.name}`."
             f"<|assistant|>Je prépare le contenu du fichier."
             f"{_tool_call('write_file', {'path': path, 'content': body})}"
             f"<|tool_result|>OK : le fichier {path} est écrit ({len(body)} octets)."
             f"<|assistant|>Je relis le fichier pour vérifier son contenu."
             f"{_tool_call('read_file', {'path': path})}"
             f"<|tool_result|>{body[:1500]}"
             f"<|assistant|>La fonction `{func.name}` est présente. Il reste à lancer ses tests.")
    out.append(convo)
    return out

