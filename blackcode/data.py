def _name_sample(arg_name: str) -> object | None:
    name = arg_name.lstrip("_").lower()
    if name in _NUM_NAMES:
        return 3
    if name in _STR_NAMES:
        return "abc"
    return None


def _arg_sample(arg: ast.arg, default) -> object | None:
    """Valeur d'argument : littérale par défaut, sinon déduite de l'annotation."""
    if default is not None:
        try:
            return ast.literal_eval(default)
        except (ValueError, SyntaxError):
            return None
    annotation = ast.unparse(arg.annotation) if arg.annotation is not None else ""
    if annotation in _TYPE_SAMPLES:
        return _TYPE_SAMPLES[annotation]
    return _name_sample(arg.arg)


def _sample_inputs(func: Func, rng: random.Random, count: int = 6) -> list[list]:
    """Entrées plausibles : valeurs par défaut, sinon types annotés simples.

    Les arguments sont des *hypothèses*. Ce n'est pas grave : le scénario
    n'est écrit que si le mutant se comporte différemment de l'original sur ces
    entrées. Une hypothèse fausse ne produit pas d'exemple, jamais un faux.
    """
    try:
        tree = ast.parse(func.body)
    except SyntaxError:
        return []
    node = tree.body[0] if tree.body else None
    if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
        return []
    if node.args.vararg or node.args.kwarg or node.args.kwonlyargs:
        return []
    args = node.args.args
    defaults = node.args.defaults
    n_req = len(args) - len(defaults)
    base: list = []
    for i, arg in enumerate(args):
        default = defaults[i - n_req] if i >= n_req else None
        value = _arg_sample(arg, default)
        if value is None:
            return []
        base.append(value)
    if not args:
        return [[]]
    pool = [base]
    for i, value in enumerate(base):
        variants = []
        if isinstance(value, bool):
            variants = [not value]
        elif isinstance(value, int):
            variants = [value + 1, value - 1, value * 2]
        elif isinstance(value, float):
            variants = [value + 1.5, value / 2]
        elif isinstance(value, str):
            variants = [value + "a", ""]
        for v in variants:
            pool.append(base[:i] + [v] + base[i + 1:])
    rng.shuffle(pool)
    return pool[:count]


def _rename_function(src: str, name: str) -> str:
    node = ast.parse(src).body[0]
    node.name = name
    return ast.unparse(node)


def mutated_failure_example(func: Func, rng: random.Random,
                            timeout: float = 3.0) -> str | None:
    """Mute une fonction, l'exécute, et rend un scénario de correction réel.

    La trace d'erreur écrite dans l'exemple est celle du processus lancé : si le
    mutant se comporte comme l'original, aucun exemple n'est produit. Aucune
    ligne de sortie n'est inventée.
    """
    mutated = mutate_function(func.body, rng)
    inputs = _sample_inputs(func, rng)
    if mutated is None or not inputs:
        return None
    orig_src, mut_src, desc = mutated
    imports = extract_imports(func.src)
    if imports:
        block = "try:\n" + "\n".join("    " + ln for ln in imports.splitlines()) \
            + "\nexcept Exception:\n    pass\n"
    else:
        block = ""
    program = (
        "import json, sys, traceback\n"
        + block
        + "def run(fn, calls):\n"
        "    out = []\n"
        "    for args in calls:\n"
        "        try:\n"
        "            out.append(['ok', repr(fn(*args))])\n"
        "        except Exception:\n"
        "            out.append(['err', traceback.format_exc(limit=2)])\n"
        "    return out\n"
        f"CALLS = {inputs!r}\n"
        + _rename_function(orig_src, "original") + "\n"
        + _rename_function(mut_src, "mutant") + "\n"
        "ref = run(original, CALLS)\n"
        "got = run(mutant, CALLS)\n"
        "print(json.dumps({'ref': ref, 'got': got}))\n"
    )
    try:
        proc = subprocess.run([sys.executable, "-I", "-c", program], capture_output=True,
                              text=True, timeout=timeout)
    except (subprocess.TimeoutExpired, OSError):
        return None
    if proc.returncode != 0:
        return None
    try:
        result = json.loads(proc.stdout.strip().splitlines()[-1])
    except (ValueError, IndexError):
        return None
    diffs = [(r, g) for r, g in zip(result["ref"], result["got"]) if r != g]
    if not diffs:
        return None
    ref, got = diffs[0]
    fr = rng.random() < 0.5
    if ref[0] == "ok" and got[0] == "ok":
        observation = (f"attendu {ref[1]}, obtenu {got[1]}" if fr
                       else f"expected {ref[1]}, got {got[1]}")
    elif ref[0] == "ok" and got[0] == "err":
        tail = got[1].strip().splitlines()[-1]
        observation = (f"exception inattendue : {tail}" if fr
                       else f"unexpected exception: {tail}")
    else:
        return None
    path = "src/target.py"
    key = "fichier"
    if fr:
        user = (f"Le test de `{func.name}` échoue : {observation}. "
                f"Voici le {key} :\n{mut_src}\nCorrige.")
        convo = (f"<|system|>{SYSTEM_FR}<|user|>{user}"
                 f"<|assistant|>J'exécute les tests pour voir l'échec."
                 f"{_tool_call('run_tests', {'path': path})}"
                 f"<|tool_result|>FAILED {func.name} — {observation}"
                 f"<|assistant|>La condition `{desc}` produit un comportement "
                 f"différent de l'attendu. Je restaure la version correcte."
                 f"{_tool_call('write_file', {'path': path, 'content': orig_src})}"
                 f"<|tool_result|>ok : {path} écrit"
                 f"<|assistant|>Je relance les tests."
                 f"{_tool_call('run_tests', {'path': path})}"
                 f"<|tool_result|>PASSED {func.name}"
                 f"<|assistant|>Corrigé : `{desc}` était la source de l'écart "
                 f"({observation}).")
    else:
        user = (f"`{func.name}` fails: {observation}. Here is the file:\n{mut_src}\n"
                f"Fix it.")
        convo = (f"<|system|>{SYSTEM_EN}<|user|>{user}"
                 f"<|assistant|>Running the tests to see the failure."
                 f"{_tool_call('run_tests', {'path': path})}"
                 f"<|tool_result|>FAILED {func.name} — {observation}"
                 f"<|assistant|>The condition `{desc}` produces a different result "
                 f"than expected. Restoring the correct version."
                 f"{_tool_call('write_file', {'path': path, 'content': orig_src})}"
                 f"<|tool_result|>ok: wrote {path}"
                 f"<|assistant|>Re-running the tests."
                 f"{_tool_call('run_tests', {'path': path})}"
                 f"<|tool_result|>PASSED {func.name}"
                 f"<|assistant|>Fixed — `{desc}` explained the mismatch "
                 f"({observation}).")
    return convo


