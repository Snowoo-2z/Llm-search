# Qualité
_ALLOWED = bytes(
    string.ascii_letters + string.digits + string.whitespace, "ascii"
)


def _alnum_ratio(text: str) -> float:
    """Part de caractères « utiles » ; chemin rapide C pour l'ASCII."""
    if not text:
        return 0.0
    if text.isascii():
        raw = text.encode("ascii", "ignore")
        return (len(raw) - len(raw.translate(None, _ALLOWED))) / len(raw)
    return sum(1 for c in text if c.isalnum() or c.isspace()) / len(text)


def _metrics(text: str) -> dict:
    lines = text.splitlines()
    n_lines = max(1, len(lines))
    non_empty = [ln for ln in lines if ln.strip()]
    lengths = [len(ln) for ln in lines] or [0]
    alnum = _alnum_ratio(text)
    uniq = len({ln.strip() for ln in non_empty}) / max(1, len(non_empty))
    return {
        "chars": len(text),
        "lines": n_lines,
        "max_line": max(lengths),
        "mean_line": sum(lengths) / n_lines,
        "alnum_ratio": alnum,
        "unique_line_ratio": uniq,
        "words": len(text.split()),
    }


def _url_density(text: str) -> float:
    urls = URL_RE.findall(text)
    if not urls:
        return 0.0
    url_chars = sum(len(u) for u in urls)
    return url_chars / max(1, len(text))

def _boilerplate_score(text: str) -> int:
    low = text.lower()
    return sum(1 for marker in BOILERPLATE_MARKERS if marker in low)

def quality_reasons(text: str, kind: str, lang: str) -> list[str]:
    """Rend la liste des motifs de rejet (vide = document accepté)."""
    if not text or not text.strip():
        return ["vide"]
    m = _metrics(text)
    if kind in ("sms", "chat", "tweet"):
        if m["chars"] < 10:
            return ["trop court"]
    else:
        if m["chars"] < 200:
            return ["trop court"]
    if m["chars"] > 600_000:
        return ["trop long"]
    low = text[:4000].lower()
    if any(marker in low for marker in GENERATED_MARKERS):
        return ["fichier généré"]
    for pattern in SECRET_PATTERNS:
        if pattern.search(text):
            return ["secret"]
    for pattern in PII_PATTERNS:
        if pattern.search(text):
            return ["donnée personnelle potentielle"]
    if kind in ("sms", "chat", "tweet"):
        if m["alnum_ratio"] < 0.15:
            return ["trop peu de texte"]
    else:
        if m["alnum_ratio"] < 0.30:
            return ["trop peu de texte"]
    # Heuristiques génériques anti-spam / boilerplate
    if _url_density(text) > 0.25 and m["words"] < 200:
        return ["trop d'urls"]
    if REPEATED_PUNCT_RE.search(text):
        return ["ponctuation répétée"]
    if _boilerplate_score(text) >= 3 and m["words"] < 120:
        return ["boilerplate"]
    if kind == "code":
        if m["mean_line"] > 160 or m["max_line"] > 4000:
            return ["minifié"]
        if m["unique_line_ratio"] < 0.35 and m["lines"] > 40:
            return ["répétitif"]
        if lang == "python":
            try:
                ast.parse(text)
            except (SyntaxError, ValueError):
                return ["python invalide"]
    else:  # documentation, prose, sms, chat, tweet
        if kind in ("sms", "chat", "tweet"):
            # SMS/tchat : tolère très court mais pas vide, garde abréviations
            if m["words"] < 3:
                return ["prose trop courte"]
        else:
            if m["words"] < 30:
                return ["prose trop courte"]
        if m["unique_line_ratio"] < 0.20 and m["lines"] > 30:
            return ["répétitif"]
        # Les lignes longues sont fréquentes dans les documents Web en JSONL
        # (une ligne par document); ne pas confondre cela avec du code minifié.
    return []


def quality_score(text: str, kind: str = "prose", lang: str = "text") -> float:
    """Score qualité 0-1 pour tri, 1 = très bon, 0 = très mauvais.

    Combine longueur, alnum_ratio, unique_line_ratio, url_density, boilerplate, français heuristique.
    Ne remplace pas quality_reasons (filtre binaire), mais aide à choisir seuil MIN_QUALITY_SCORE.
    """
    m = _metrics(text)
    score = 1.0
    # longueur : pénalise très court et très long, mais tolère SMS/chat court
    if kind in ("sms", "chat", "tweet"):
        if m["chars"] < 20:
            score *= 0.7
    else:
        if m["chars"] < 400:
            score *= 0.5
        elif m["chars"] > 100000:
            score *= 0.8
    # alnum_ratio
    if m["alnum_ratio"] < 0.4:
        score *= 0.5 if kind not in ("sms", "chat", "tweet") else 0.8
    elif m["alnum_ratio"] < 0.6:
        score *= 0.8
    # unique
    if m["unique_line_ratio"] < 0.3:
        score *= 0.6
    # url density
    ud = _url_density(text)
    if ud > 0.3:
        score *= 0.3
    elif ud > 0.15:
        score *= 0.7
    # boilerplate
    bp = _boilerplate_score(text)
    if bp >= 4:
        score *= 0.4
    elif bp >= 2:
        score *= 0.8
    # français heuristique pour prose
    if kind != "code":
        fr = _french_heuristic_score(text)
        score *= (0.5 + 0.5 * fr)  # fr 0->0.5, 1->1.0
    # ponctuation répétée
    if REPEATED_PUNCT_RE.search(text):
        score *= 0.5
    # bonus abréviations RS françaises (slt, bjr, mdr, etc.) pour sms/chat
    if kind in ("sms", "chat", "tweet"):
        low = text.lower()
        abbrev_markers = ("mdr", "ptdr", "slt", "bjr", "stp", "tkt", "dsl", "pk", "bcp", "slt", "cc", "a+", "biz")
        if any(a in low for a in abbrev_markers):
            score = min(1.0, score * 1.15)
    return max(0.0, min(1.0, score))

def is_quality(text: str, kind: str, lang: str) -> bool:
    return not quality_reasons(text, kind, lang)


