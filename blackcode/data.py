# Assemblage
def train_tokenizer(docs: list[Doc], vocab: int, out: Path, sample_chars: int = 120_000_000,
                    seed: int = 0) -> None:
    from tokenizers import ByteLevelBPETokenizer
    rng = random.Random(seed)
    order = list(range(len(docs)))
    rng.shuffle(order)

    def iterator():
        used = 0
        for i in order:
            yield docs[i].text
            used += len(docs[i].text)
            if used >= sample_chars:
                break

    print(f"[tokenizer] BPE byte-level vocab={vocab}, "
          f"{min(len(docs), len(order))} documents, échantillon≤{sample_chars/1e6:.0f} M car.")
    tok = ByteLevelBPETokenizer()
    tok.train_from_iterator(iterator(), vocab_size=vocab, min_frequency=2,
                            special_tokens=SPECIAL_TOKENS, show_progress=False)
    tok.save(str(out / "tokenizer.json"))
    (out / "tokenizer_config.json").write_text(json.dumps({
        "type": "ByteLevelBPE", "vocab_size": vocab,
        "special_tokens": SPECIAL_TOKENS, "eos_token": EOS,
    }, indent=2))
    print(f"[tokenizer] {out/'tokenizer.json'} "
          f"({(out/'tokenizer.json').stat().st_size/1024:.0f} Ko)")


def load_tokenizer_size(path: Path) -> int:
    from tokenizers import Tokenizer
    return Tokenizer.from_file(str(path)).get_vocab_size()


def load_external_tokenizer(spec: str, out: Path) -> Path:
    """Copie un tokenizer existant en ajoutant nos jetons spéciaux à la fin.

    L'ajout en fin de vocabulaire **ne modifie aucun identifiant existant** :
    c'est la condition pour que les logits d'un professeur (StarCoder2, 49 152
    jetons) restent alignés avec ceux de l'élève. Sans cela, la distillation au
    niveau des logits est impossible.
    """
    from tokenizers import Tokenizer
    tok = Tokenizer.from_pretrained(spec[3:]) if spec.startswith("hf:") \
        else Tokenizer.from_file(spec)
    before = tok.get_vocab_size()
    missing = [t for t in SPECIAL_TOKENS if tok.token_to_id(t) is None]
    if missing:
        tok.add_special_tokens(missing)
    tok.save(str(out / "tokenizer.json"))
    print(f"[tokenizer] {spec} : {before} jetons + {len(missing)} spéciaux "
          f"= {tok.get_vocab_size()} (identifiants existants inchangés)")
    return out / "tokenizer.json"


def pack(docs: list[Doc], tokenizer_path: Path, out: Path, seq_len: int,
         fim_rate: float, val_frac: float, seed: int) -> dict:
    """Écrit train.bin/val.bin : chaque document devient un bloc ≤ seq_len.

    Contrairement à la v1 (flux continu), on garde un exemple = un document ou
    une conversation réelle. Le remplissage aléatoire n'apprend rien ; les
    documents longs sont découpés en fenêtres contiguës avec chevauchement nul,
    et le FIM est appliqué avant tokenisation.
    """
    from tokenizers import Tokenizer
    tok = Tokenizer.from_file(str(tokenizer_path))
    eos_id = tok.token_to_id(EOS)
    assert eos_id is not None
    fim_tokens = resolve_fim_tokens(tok)
    rng = random.Random(seed)
    order = list(range(len(docs)))
    rng.shuffle(order)
    n_val = max(1, int(len(docs) * val_frac)) if len(docs) > 10 else 0
    val_idx = set(order[:n_val])

    files = {False: (out / "train.bin").open("wb"), True: (out / "val.bin").open("wb")}
    counts = {"train": 0, "val": 0, "docs": 0, "truncated": 0, "fim": 0}
    lengths: list[int] = []
    by_kind: dict[str, int] = {}
    try:
        for i, doc in enumerate(docs):
            text = doc.text
            if doc.kind != "agentic" and fim_rate > 0 and rng.random() < fim_rate:
                fim = fim_example(text, rng, fim_tokens)
                if fim is not None:
                    text = fim
                    counts["fim"] += 1
            ids = tok.encode(text, add_special_tokens=False).ids
            if len(ids) > seq_len:
                # fenêtres de seq_len, sans chevauchement
                windows = [ids[j:j + seq_len] for j in range(0, len(ids), seq_len)]
                if len(windows[-1]) < seq_len // 8:
                    windows.pop()
                counts["truncated"] += 1
            else:
                windows = [ids]
            is_val = i in val_idx
            fh = files[is_val]
            for w in windows:
                arr = np.asarray(w + [eos_id], dtype=np.uint16)
                arr.tofile(fh)
                counts["val" if is_val else "train"] += len(arr)
                lengths.append(len(arr))
            counts["docs"] += 1
            by_kind[doc.kind] = by_kind.get(doc.kind, 0) + 1
    finally:
        for fh in files.values():
            fh.close()

    lengths.sort()
    meta = {
        "vocab_size": tok.get_vocab_size(),
        "train_tokens": counts["train"],
        "val_tokens": counts["val"],
        "documents": counts["docs"],
        "documents_truncated": counts["truncated"],
        "fim_documents": counts["fim"],
        "by_kind": by_kind,
        "seq_len": seq_len,
        "p50_example_tokens": lengths[len(lengths) // 2] if lengths else 0,
        "p90_example_tokens": lengths[int(len(lengths) * 0.9)] if lengths else 0,
        "eos_id": eos_id,
        "tokenizer": str(tokenizer_path),
        "seed": seed,
    }
    (out / "meta.json").write_text(json.dumps(meta, indent=2) + "\n")
    return meta


