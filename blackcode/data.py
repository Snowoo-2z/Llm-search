# FIM (fill-in-the-middle) : rend le modèle utilisable pour compléter du code
FIM_FALLBACKS = [  # ordre de préférence : nos jetons, puis StarCoder2
    (FIM_BEGIN, FIM_HOLE, FIM_END),
    ("<fim_prefix>", "<fim_middle>", "<fim_suffix>"),
]


def resolve_fim_tokens(tok) -> tuple[str, str, str]:
    """Choisit les jetons FIM déjà présents (StarCoder2 utilise <fim_prefix>…)."""
    for triple in FIM_FALLBACKS:
        if all(tok.token_to_id(t) is not None for t in triple):
            return triple
    return FIM_BEGIN, FIM_HOLE, FIM_END


def fim_example(text: str, rng: random.Random,
                tokens: tuple[str, str, str] | None = None) -> str | None:
    lines = text.splitlines(keepends=True)
    if len(lines) < 8:
        return None
    n = len(lines)
    start = rng.randint(1, max(1, n // 2))
    end = rng.randint(start, n - 1)
    if end == start:
        return None
    begin_tok, hole_tok, end_tok = tokens or (FIM_BEGIN, FIM_HOLE, FIM_END)
    return (begin_tok + "".join(lines[:start]) + hole_tok
            + "".join(lines[end:]) + end_tok + "".join(lines[start:end]))


