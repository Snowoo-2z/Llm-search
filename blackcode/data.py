# Collecte
def iter_paths(src: Path, exts: set[str], min_bytes: int, max_bytes: int):
    for path in sorted(src.rglob("*")):
        if not path.is_file():
            continue
        if any(part.startswith(".") or part in {"__pycache__", "node_modules", ".git"}
               for part in path.parts):
            continue
        if path.suffix not in exts:
            continue
        size = path.stat().st_size
        if min_bytes <= size <= max_bytes:
            yield path


def doc_from_path(path: Path) -> Doc | None:
    lang = LANG_BY_EXT.get(path.suffix)
    if lang is None:
        return None
    text = read_text(path)
    if text is None:
        return None
    kind = "prose" if lang in PROSE_LANGS else "code"
    return Doc(text=text, lang=lang, kind=kind, path=str(path),
               licence=detect_licence(text, path))


