# Chargement des données tokenisées (compatibilité v1/v2) — version optimisée
class TokenDataset:
    """Memmap uint16 des .bin produits par `corpus.prepare` ou `data.build`.

    Optimisations :
    - pin_memory + non_blocking déjà présent
    - torch.randint au lieu de np.random.randint (plus rapide, pas de GIL)
    - np.stack remplacé par boucle torch pour éviter 2 copies
    - cache train_torch pour éviter conversion numpy→torch répétée si RAM suffisante (optionnel)
    """

    def __init__(self, data_dir: str | Path, device: str = "cpu", use_torch_cache: bool = False):
        import torch  # import local : le pipeline de données n'en a pas besoin

        self.dir = Path(data_dir)
        meta_path = self.dir / "meta.json"
        if not meta_path.exists():
            raise FileNotFoundError(
                f"{meta_path} absent : lancer d'abord `python -m blackcode.data build`"
            )
        self.meta = json.loads(meta_path.read_text())
        self.train = np.memmap(self.dir / "train.bin", dtype=np.uint16, mode="r")
        val_path = self.dir / "val.bin"
        self.val = (np.memmap(val_path, dtype=np.uint16, mode="r")
                    if val_path.exists() and val_path.stat().st_size > 0 else self.train)
        self.device = device
        self._torch = torch
        # Optionnel : cache torch en RAM pour 4 Go = 2B tokens uint16 = 4 Go RAM → trop gros pour T4, donc désactivé par défaut
        self._train_torch = None
        self._val_torch = None
        if use_torch_cache:
            try:
                self._train_torch = torch.from_numpy(np.array(self.train, dtype=np.uint16)).pin_memory()
                if val_path.exists():
                    self._val_torch = torch.from_numpy(np.array(self.val, dtype=np.uint16)).pin_memory()
                print(f"[data] torch cache activé : {len(self.train)/1e6:.1f}M tokens en RAM")
            except Exception as exc:
                print(f"[data] torch cache échec : {exc}")
                self._train_torch = None

    def get_batch(self, split: str, batch_size: int, seq_len: int):
        torch = self._torch
        if self._train_torch is not None and split == "train":
            data_torch = self._train_torch
            data_len = len(data_torch)
            if data_len < seq_len + 2:
                raise ValueError(f"{split} ne contient que {data_len} tokens")
            # torch.randint plus rapide que np.random.randint, évite GIL
            ix = torch.randint(0, data_len - seq_len - 1, (batch_size,))
            # slicing direct sur tensor pin_memory
            x = torch.stack([data_torch[i:i+seq_len].to(torch.int64) for i in ix])
            y = torch.stack([data_torch[i+1:i+1+seq_len].to(torch.int64) for i in ix])
            if self.device.startswith("cuda"):
                x = x.to(self.device, non_blocking=True)
                y = y.to(self.device, non_blocking=True)
            else:
                x = x.to(self.device)
                y = y.to(self.device)
            return x, y

        # fallback memmap numpy (défaut, économe RAM)
        data = self.train if split == "train" else self.val
        if len(data) < seq_len + 2:
            raise ValueError(f"{split} ne contient que {len(data)} tokens")
        # torch.randint pour ix même si data est numpy (évite GIL numpy)
        ix = torch.randint(0, len(data) - seq_len - 1, (batch_size,)).numpy()
        # astype int64 + from_numpy en une étape, évite double copie
        x = np.empty((batch_size, seq_len), dtype=np.int64)
        y = np.empty((batch_size, seq_len), dtype=np.int64)
        for b, i in enumerate(ix):
            # copy directe, évite np.stack intermédiaire
            x[b] = data[i:i+seq_len]
            y[b] = data[i+1:i+1+seq_len]
        x = torch.from_numpy(x)
        y = torch.from_numpy(y)
        if self.device.startswith("cuda"):
            x = x.pin_memory().to(self.device, non_blocking=True)
            y = y.pin_memory().to(self.device, non_blocking=True)
        else:
            x = x.to(self.device)
            y = y.to(self.device)
        return x, y

    @property
    def train_tokens(self) -> int:
        return int(self.meta["train_tokens"])

    @property
    def val_tokens(self) -> int:
        return int(self.meta["val_tokens"])
