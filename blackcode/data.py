def iter_hf_docs(spec: str, split: str, text_field: str, budget: int,
                 keep_if: re.Pattern | None = None, license_field: str = "license"): 
    """Itère un dataset HuggingFace en flux (pas de téléchargement complet).

    `spec` vaut ``"organisation/nom"`` ou ``"organisation/nom:config"``, par
    exemple ``bigcode/the-stack-smol:python`` ou ``HuggingFaceFW/fineweb-2:fra``.
    Nécessite le paquet `datasets` (présent sur Colab, pas dans les tests).
    """
    from datasets import load_dataset

    name, _, config = spec.partition(":")
    print(f"[hf] {name}" + (f" [{config}]" if config else "") + f" (split={split}, flux)")
    ds = load_dataset(name, config or None, split=split, streaming=True)
    lang = config if config in set(LANG_BY_EXT.values()) else "text"
    # Détection kind pour discussions RS avec abréviations
    spec_lower = spec.lower()
    if any(k in spec_lower for k in ("sms", "88mil", "comere")):
        kind = "sms"
    elif any(k in spec_lower for k in ("chat", "irc", "getalp", "tchat")):
        kind = "chat"
    elif any(k in spec_lower for k in ("tweet", "polititweet")):
        kind = "tweet"
    else:
        kind = "prose" if lang in PROSE_LANGS else "code"
    # Licence de la base de données connue; les droits/conditions des pages
    # sources restent à vérifier séparément (p. ex. Common Crawl).
    dataset_licence = (
        "odc-by-1.0"
        if name.casefold() in {"huggingfacefw/fineweb-2", "epfml/fineweb2-hq"}
        else "cc-by-4.0"
        if any(x in name.lower() for x in ("comere", "88mil", "smslareunion", "ortolang"))
        else "?"
    )
    used = 0
    seen = 0
    for row in ds:
        text = row.get(text_field)
        if not isinstance(text, str) or not text:
            continue
        if keep_if is not None and not keep_if.search(text):
            continue
        seen += 1
        used += len(text)
        if used > budget:
            break
        metadata = {
            "hf_row": True,
            "dataset_id": name,
            "dataset_config": config or None,
            "dataset_license": dataset_licence,
            "license_scope": "dataset packaging; not underlying text rights",
        }
        for key in ("quality_score", "language_score"):
            if isinstance(row.get(key), (int, float)):
                metadata[key] = float(row[key])
        record_license = row.get(license_field) if license_field else None
        if isinstance(record_license, str) and record_license.strip():
            metadata["record_license"] = record_license.strip()
        elif isinstance(record_license, list):
            metadata["record_license"] = [str(x).strip() for x in record_license if str(x).strip()]
        for key in ("url", "identifier", "collection", "open_type", "date", "dump", "language"):
            value = row.get(key)
            if isinstance(value, (str, int, float)):
                metadata[key] = value
        source_url = metadata.get("url")
        if isinstance(source_url, str):
            metadata["source_url"] = source_url
        yield Doc(text, lang, kind, path=f"hf:{name}:{config}",
                  licence=dataset_licence, meta=metadata)


def build(args) -> dict:
    srcs = [Path(s) for s in args.src]
    exts = {e if e.startswith(".") else "." + e for e in args.exts.split(",")}
    dedup = Deduper(near=not args.no_near)
    stats = {"files": 0, "rejected_quality": 0, "rejected_dup": 0,
             "rejected_language": 0, "rejected_score": 0,
             "rejected_licence": 0, "rejected_record_license": 0,
             "kept": 0, "bytes": 0,
             "by_reason": {}, "by_lang": {}, "by_kind": {}, "licences": {},
             "record_licenses": {}}
    docs: list[Doc] = []
    budget = args.max_mb * 1024 * 1024
    used = 0

    keep_if = re.compile(args.keep_if) if getattr(args, "keep_if", None) else None

    def accept(doc: Doc) -> bool:
        stats["files"] += 1
        if getattr(args, "french_only", False) and doc.kind != "code":
            if not is_french_prose(doc.text):
                stats["rejected_language"] += 1
                return False
        min_score = float(getattr(args, "min_quality_score", 0.0))
        if min_score > 0:
            score = doc.meta.get("quality_score")
            if not isinstance(score, (int, float)) or score < min_score:
                stats["rejected_score"] += 1
                return False
        if doc.meta.get("hf_row"):
            record_license = doc.meta.get("record_license")
            if getattr(args, "require_hf_license", False) and not record_license:
                stats["rejected_record_license"] += 1
                return False
            allowed = {normalize_licence_label(x)
                       for x in (getattr(args, "allowed_hf_license", None) or [])}
            if allowed:
                labels = record_license if isinstance(record_license, list) else [record_license]
                normalized = {normalize_licence_label(x) for x in labels if x}
                if not normalized or not normalized.issubset(allowed):
                    stats["rejected_record_license"] += 1
                    return False
        if args.licence == "permissive" and doc.licence not in PERMISSIVE:
            stats["rejected_licence"] += 1
            return False
        reasons = quality_reasons(doc.text, doc.kind, doc.lang)
        if reasons:
            stats["rejected_quality"] += 1
            key = reasons[0]
            stats["by_reason"][key] = stats["by_reason"].get(key, 0) + 1
            return False
        dup = dedup.check(doc.text)
        if dup:
            stats["rejected_dup"] += 1
            key = f"doublon {dup}"
            stats["by_reason"][key] = stats["by_reason"].get(key, 0) + 1
            return False
        docs.append(doc)
        stats["kept"] += 1
        stats["bytes"] += len(doc.text.encode("utf-8"))
        stats["by_lang"][doc.lang] = stats["by_lang"].get(doc.lang, 0) + 1
        stats["by_kind"][doc.kind] = stats["by_kind"].get(doc.kind, 0) + 1
        stats["licences"][doc.licence] = stats["licences"].get(doc.licence, 0) + 1
        rl = doc.meta.get("record_license")
        if rl:
            if isinstance(rl, list):
                for r in rl:
                    stats["record_licenses"][r] = stats["record_licenses"].get(r, 0) + 1
            else:
                stats["record_licenses"][rl] = stats["record_licenses"].get(rl, 0) + 1
        return True

    for src in srcs:
        if not src.exists():
            print(f"[data] source absente : {src}", file=sys.stderr)
            continue
        for path in iter_paths(src, exts, args.min_bytes, args.max_bytes):
            if used >= budget:
                break
            doc = doc_from_path(path)
            if doc is None:
                continue
            if accept(doc):
                used += len(doc.text.encode("utf-8"))

    for spec in getattr(args, "hf", None) or []:
        if used >= budget:
            break
        try:
            for doc in iter_hf_docs(spec, args.hf_split, args.hf_field,
                                    budget - used, keep_if,
                                    getattr(args, 'hf_license_field', 'license')):
                if accept(doc):
                    used += len(doc.text.encode("utf-8"))
                if used >= budget:
                    break
        except Exception as exc:  # réseau, dataset gated, paquet absent
            print(f"[hf] échec sur {spec} : {exc}", file=sys.stderr)

    # Agentique : fabriqué à partir des fichiers Python retenus, pas inventé.
    agentic: list[Doc] = []
    if args.agentic_frac > 0:
        rng = random.Random(args.seed)
        py = [d for d in docs if d.lang == "python"]
        rng.shuffle(py)
        target = int(len(docs) * args.agentic_frac)
        spawns = 0
        for doc in py:
            # `--max-spawns` limite les *exécutions*, pas la génération des
            # gabarits : sinon un petit budget d'exécution tronque tout le jeu.
            if len(agentic) >= target:
                break
            for func in functions_from_source(doc.text):
                if len(func.body) < 80:
                    continue
                if args.agentic_exec and spawns < args.max_spawns:
                    spawns += 1
                    convo = mutated_failure_example(func, rng)
                    if convo:
                        agentic.append(Doc(convo, "python", "agentic", doc.path, doc.licence))
                for convo in agentic_examples(func, rng):
                    agentic.append(Doc(convo, "python", "agentic", doc.path, doc.licence))
                if len(agentic) >= target:
                    break
    if agentic:
        executed = sum(1 for d in agentic if "run_tests" in d.text and "ÉCHEC" in d.text)
        print(f"[data] {len(agentic)} exemples agentiques dont {executed} "
              f"issus d'une exécution réelle ({spawns} mutants exécutés)")
        docs.extend(agentic)
        rng = random.Random(args.seed)
        rng.shuffle(docs)
        stats["by_kind"]["agentic"] = len(agentic)

    stats["tokens_estimate"] = int(stats["bytes"] / 4.2)
    return {"docs": docs, "stats": stats}


def cmd_stats(args) -> None:
    result = build(argparse.Namespace(**{**vars(args), "max_mb": args.max_mb,
                                         "agentic_frac": 0.0, "agentic_exec": False,
                                         "max_spawns": 0, "licence": "all"}))
    stats = result["stats"]
    stats["docs"] = len(result["docs"])
    print(json.dumps(stats, indent=2, ensure_ascii=False))


def cmd_build(args) -> None:
    if not 0.0 <= args.min_quality_score <= 1.0:
        raise SystemExit("--min-quality-score doit être compris entre 0 et 1")
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    result = build(args)
    docs = result["docs"]
    if not docs:
        sys.exit("Aucun document retenu — vérifier --src et les extensions.")
    print(f"[data] {len(docs)} documents, {result['stats']['bytes']/1e6:.1f} Mo "
          f"({result['stats']['tokens_estimate']/1e6:.1f} M tokens estimés)")
    if args.tokenizer:
        load_external_tokenizer(args.tokenizer, out)
    else:
        train_tokenizer(docs, args.vocab, out, sample_chars=args.tokenizer_chars, seed=args.seed)
    actual_vocab = load_tokenizer_size(out / "tokenizer.json")
    if actual_vocab > args.vocab:
        print(f"[tokenizer] ⚠ le tokenizer fait {actual_vocab} jetons, "
              f"--vocab {args.vocab} : les configs de modèle doivent utiliser "
              f"vocab_size ≥ {actual_vocab} (voir --sync-config).")
    if args.sync_config:
        for cfg_path in args.sync_config:
            cfg_file = Path(cfg_path)
            cfg = json.loads(cfg_file.read_text())
            cfg["vocab_size"] = actual_vocab
            cfg_file.write_text(json.dumps(cfg, indent=2, ensure_ascii=False) + "\n")
            print(f"[config] {cfg_file} : vocab_size = {actual_vocab}")
    meta = pack(docs, out / "tokenizer.json", out, args.seq_len, args.fim_rate,
                args.val_frac, args.seed)
    meta["french_only_prose"] = bool(getattr(args, "french_only", False))
    meta["stats"] = result["stats"]
    (out / "meta.json").write_text(json.dumps(meta, indent=2, ensure_ascii=False) + "\n")
    print(json.dumps({k: meta[k] for k in
                      ("train_tokens", "val_tokens", "documents", "fim_documents",
                       "by_kind", "p50_example_tokens", "p90_example_tokens")},
                     indent=2, ensure_ascii=False))


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description="Pipeline de données BlackCode v2")
    sub = p.add_subparsers(dest="command", required=True)

    def common(sp):
        sp.add_argument("--src", action="append", required=True,
                        help="répertoire source (répétable)")
        sp.add_argument("--exts", default=".py,.pyi,.js,.jsx,.ts,.tsx,.md,.mdx,.rst,.txt,"
                                          ".rs,.go,.java,.c,.h,.cpp,.sh,.sql,.yaml,.toml")
        sp.add_argument("--min-bytes", type=int, default=400)
        sp.add_argument("--max-bytes", type=int, default=400_000)
        sp.add_argument("--max-mb", type=int, default=12_000)
        sp.add_argument("--no-near", action="store_true", help="désactive la quasi-dédup")
        sp.add_argument("--licence", choices=["all", "permissive"], default="all")
        sp.add_argument("--keep-if", default=None,
                        help="regex : ne garde que les documents qui la contiennent")
        sp.add_argument("--french-only", action="store_true",
                        help="filtre la prose pour ne garder que le français (requiert lingua-language-detector); les corpus de code restent inchangés")
        sp.add_argument("--hf", action="append", default=None,
                        help="dataset HuggingFace 'nom' ou 'nom:config' (répétable)")
        sp.add_argument("--hf-split", default="train")
        sp.add_argument("--hf-field", default="content")
        sp.add_argument("--hf-license-field", default="license",
                        help="champ contenant la licence par enregistrement (ex: Common Corpus)")
        sp.add_argument("--require-hf-license", action="store_true",
                        help="rejette les enregistrements HF sans licence par ligne")
        sp.add_argument("--allowed-hf-license", action="append", default=None,
                        help="allowlist de licences par enregistrement (normalisées, répétable); ex: 'MIT', 'CC0', 'public domain'")
        sp.add_argument("--seed", type=int, default=1337)

    s = sub.add_parser("stats", help="audit sans écrire de corpus")
    common(s)
    s.set_defaults(func=cmd_stats)

    b = sub.add_parser("build", help="construit data/<out>/{train.bin,val.bin,tokenizer.json}")
    common(b)
    b.add_argument("--out", required=True)
    b.add_argument("--vocab", type=int, default=49_152)
    b.add_argument("--seq-len", type=int, default=8192)
    b.add_argument("--val-frac", type=float, default=0.02)
    b.add_argument("--fim-rate", type=float, default=0.5)
    b.add_argument("--agentic-frac", type=float, default=0.0,
                   help="part du corpus transformée en trajectoires d'outils")
    b.add_argument("--agentic-exec", action="store_true",
                   help="exécute réellement les mutants (lent, mais traces vraies)")
    b.add_argument("--max-spawns", type=int, default=2000)
    b.add_argument("--min-quality-score", type=float, default=0.0,
                   help="seuil inclusif sur le champ quality_score HF (0 = aucun seuil; audit avant de choisir)")
    b.add_argument("--tokenizer-chars", type=int, default=120_000_000)
    b.add_argument("--sync-config", action="append", default=None,
                   help="fichier de config à mettre à jour avec le vocabulaire réel "
                        "(répétable)")
    b.add_argument("--tokenizer", default=None,
                   help="'hf:bigcode/starcoder2-3b' ou chemin tokenizer.json — "
                        "indispensable pour distiller un professeur (identifiants partagés)")
    b.set_defaults(func=cmd_build)
    return p


def main(argv=None) -> None:
    parser = build_parser()
    args = parser.parse_args(argv)
    args.func(args)


if __name__ == "__main__":
    main()


