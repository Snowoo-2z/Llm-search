"""Pipeline de données de BlackCode : qualité, déduplication, FIM, agentique.

Ce module transforme des sources brutes (arborescences de code, JSONL, datasets
HuggingFace exportés) en un corpus prêt à entraîner, avec trois différences par
rapport à `blackcode.corpus` (v1) :

1. **filtrage qualité** — minified, fichiers générés, secrets, lignes
   anormalement longues, code dupliqué ;
2. **déduplication exacte + quasi-dupliquée** (SimHash 64 bits, LSH par bandes) ;
3. **formats d'entraînement** — texte brut (pré-entraînement), FIM (complétion
   au milieu, ce qui rend le modèle utilisable en IDE), et trajectoires
   agentiques (appels d'outils), en français et en anglais.

Rien ici n'exécute de code par défaut. `--agentic-exec` active la génération de
scénarios de correction *réellement exécutés* : on mute une fonction, on lance
la version mutée sur des entrées générées, et on n'écrit la trace de l'erreur
que si elle a vraiment eu lieu. Aucune sortie n'est inventée.

Exemples :

    # audit d'un répertoire, sans rien écrire
    python -m blackcode.data stats --src data/raw --src /tmp/fr_docs

    # construction du corpus v2
    python -m blackcode.data build --src data/raw --out data/v2 \
        --vocab 49152 --seq-len 8192 --fim-rate 0.5 --agentic-frac 0.12
"""
