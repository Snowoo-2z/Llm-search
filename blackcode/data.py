def read_text(path: Path) -> str | None:
    try:
        return path.read_text(encoding="utf-8")
    except (UnicodeDecodeError, OSError):
        return None


def detect_licence(text: str, path: Path = Path(".")) -> str:
    """Devine la licence à partir du texte (SPDX en tête) ou du nom de fichier."""
    head = text[:4000].lower()
    for name, needles in LICENCE_HINTS:
        if any(n in head for n in needles):
            return name
    for parent in list(path.parents)[:6]:
        for fname in ("LICENSE", "LICENSE.md", "LICENSE.txt", "COPYING", "LICENCE"):
            f = parent / fname
            if f.is_file() and f.stat().st_size < 200_000:
                body = (read_text(f) or "").lower()[:20000]
                for name, needles in LICENCE_HINTS:
                    if any(n in body for n in needles):
                        return name
    return "?"


