def _tool_call(name: str, args: dict) -> str:
    return "<|tool|>" + name + "(" + json.dumps(args, ensure_ascii=False) + ")"


def agentic_examples(func: Func, rng: random.Random) -> list[str]:
    """Tâches d'écriture/lecture/outil ancrées dans une fonction réelle.

    Aucune trace d'exécution n'est fabriquée ici : ce sont des scénarios
    d'édition et de lecture. Les scénarios avec erreur réelle viennent de
    `mutated_failure_example`, qui exécute vraiment le code.
    """
    lang = "fr" if rng.random() < 0.5 else "en"
    doc = _clean_doc(func.docstring)
    path = f"src/module_{rng.randint(0, 40)}.py"
    out: list[str] = []

    if lang == "fr":
        task = (f"Implémente la fonction `{func.name}{func.signature}`."
                + (f" Elle doit : {doc}" if doc else ""))
        answer = (f"<|assistant|>{func.body}\n\n"
                  f"J'ai écrit la fonction dans `{path}`.")
        out.append(f"<|system|>{SYSTEM_FR}<|user|>{task}{answer}")
        task2 = f"Explique ce que fait `{func.name}` puis propose une version plus lisible."
        answer2 = (f"<|assistant|>{func.name} prend les arguments {func.signature} et "
                   f"{'renvoie : ' + doc if doc else 'traite les entrées fournies'}. "
                   f"Voici le corps actuel :\n{func.body}")
        out.append(f"<|system|>{SYSTEM_FR}<|user|>{task2}{answer2}")
    else:
        task = (f"Implement `{func.name}{func.signature}`."
                + (f" It should {doc}." if doc else ""))
        answer = (f"<|assistant|>{func.body}\n\n"
                  f"Done — the function is now in `{path}`.")
        out.append(f"<|system|>{SYSTEM_EN}<|user|>{task}{answer}")
        task2 = f"Walk me through `{func.name}` and make it easier to read."
        answer2 = (f"<|assistant|>`{func.name}{func.signature}` — "
                   f"{doc or 'processes the given inputs'}. Current body:\n{func.body}")
        out.append(f"<|system|>{SYSTEM_EN}<|user|>{task2}{answer2}")

    # Scénario d'outil : écrire puis relire le fichier (format teaché explicitement).
    if lang == "fr":
        convo = (f"<|system|>{SYSTEM_FR}<|user|>Crée `{path}` avec la fonction "
                 f"`{func.name}`."
                 f"<|assistant|>Je commence par écrire le fichier."
                 f"{_tool_call('write_file', {'path': path, 'content': func.body})}"
                 f"<|tool_result|>ok : {path} écrit ({len(func.body)} octets)"
                 f"<|assistant|>Le fichier est en place. Je vérifie son contenu."
                 f"{_tool_call('read_file', {'path': path})}"
                 f"<|tool_result|>{func.body[:1500]}"
                 f"<|assistant|>`{func.name}` est prête à être testée.")
    else:
        convo = (f"<|system|>{SYSTEM_EN}<|user|>Create `{path}` containing "
                 f"`{func.name}`."
                 f"<|assistant|>Writing the file first."
                 f"{_tool_call('write_file', {'path': path, 'content': func.body})}"
                 f"<|tool_result|>ok: wrote {path} ({len(func.body)} bytes)"
                 f"<|assistant|>File created. Let me read it back to confirm."
                 f"{_tool_call('read_file', {'path': path})}"
                 f"<|tool_result|>{func.body[:1500]}"
                 f"<|assistant|>`{func.name}` is ready to test.")
    out.append(convo)
    return out


# --- mutation + exécution réelle -------------------------------------------
_CMP_SWAPS = {
    ast.Eq: ast.NotEq, ast.NotEq: ast.Eq,
    ast.Lt: ast.LtE, ast.LtE: ast.Lt,
    ast.Gt: ast.GtE, ast.GtE: ast.Gt,
    ast.In: ast.NotIn, ast.NotIn: ast.In,
}


_CMP_SYMBOLS = {
    ast.Eq: "==", ast.NotEq: "!=", ast.Lt: "<", ast.LtE: "<=",
    ast.Gt: ">", ast.GtE: ">=", ast.In: "in", ast.NotIn: "not in",
}


def _collect_comparisons(node: ast.AST) -> list[tuple[ast.Compare, int]]:
    """Liste ordonnée et déterministe des opérateurs de comparaison."""
    out: list[tuple[ast.Compare, int]] = []

    class Visitor(ast.NodeVisitor):
        def visit_Compare(self, n: ast.Compare) -> None:
            out.extend((n, k) for k in range(len(n.ops)))
            self.generic_visit(n)

    Visitor().visit(node)
    return out


def mutate_function(body: str, rng: random.Random) -> tuple[str, str, str] | None:
    """Mute un opérateur de comparaison, au niveau AST (donc toujours valide).

    Une mutation textuelle produit des erreurs de syntaxe (`->` devenu `->=`,
    `>=` dans une annotation). Passer par l'AST garantit que le mutant est
    exécutable ; `ast.unparse` normalise la mise en forme, ce qui est le seul
    compromis.
    """
    try:
        node = ast.parse(body).body[0]
    except (SyntaxError, ValueError, IndexError):
        return None
    if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
        return None
    candidates = _collect_comparisons(node)
    if not candidates:
        return None
    target = rng.randrange(len(candidates))
    mutated = copy.deepcopy(node)
    cmp_node, k = _collect_comparisons(mutated)[target]
    swap = _CMP_SWAPS.get(type(cmp_node.ops[k]))
    if swap is None:
        return None
    desc = f"{_CMP_SYMBOLS.get(type(cmp_node.ops[k]), '?')} → {_CMP_SYMBOLS.get(swap, '?')}"
    cmp_node.ops[k] = swap()
    return ast.unparse(node), ast.unparse(mutated), desc

def extract_imports(src: str) -> str:
    """Rend les imports de premier niveau du module (pour exécuter une fonction)."""
    try:
        tree = ast.parse(src)
    except (SyntaxError, ValueError):
        return ""
    lines = []
    for node in tree.body:
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            try:
                lines.append(ast.unparse(node))
            except (AttributeError, ValueError):
                continue
    return "\n".join(lines)


